/* Les phrases d'une leçon, dans l'ordre du support, sans doublon. */
function phrasesSupport(l) {
  const vues = new Set(), out = [];
  (PHRASES_SUPPORTS[l] || []).forEach(([groupe, lignes]) => lignes.forEach(([qui, hanzi, pinyin, fr]) => {
    const k = normHanzi(hanzi);
    if (vues.has(k)) return;
    vues.add(k); out.push({ groupe, qui, hanzi, pinyin, fr });
  }));
  return out;
}
